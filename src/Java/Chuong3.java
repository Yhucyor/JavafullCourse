package Java;

public class Chuong3 {
    public static void main(String[] args) {
        // CHƯƠNG 3: VÒNG LẶP //

        //1. Vòng lặp For
        for(int i = 0; i < 3; i++){
            System.out.println(i);
        }

        //2. Vòng lặp While
        int i = 2;
        while(i >= 0){
            System.out.println("Thực hiện vòng lặp While");
            i--;
        }
    }
}
